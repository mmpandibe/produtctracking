<#
.SYNOPSIS
  Regenerates deploy/sql/02-schema.sql from the EF Core migrations (run after adding a migration, before a release).
  The script is idempotent: on the server it applies only the migrations a database doesn't have yet.
#>
$ErrorActionPreference = 'Stop'
$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\..'))
$out = Join-Path $PSScriptRoot '02-schema.sql'
$tmp = Join-Path $env:TEMP 'npro-schema.sql'
Push-Location (Join-Path $root 'server')
try {
  dotnet ef migrations script --idempotent -p src/Npro.Infrastructure -s src/Npro.Api -o $tmp
  if ($LASTEXITCODE -ne 0) { throw 'dotnet ef migrations script failed' }
}
finally { Pop-Location }
$migrations = (Get-ChildItem (Join-Path $root 'server\src\Npro.Infrastructure\Migrations') -Filter '2*.cs' |
  Where-Object Name -notlike '*.Designer.cs' | Sort-Object Name | ForEach-Object { ($_.BaseName -split '_', 2)[1] }) -join ', '
$header = @"
/*
  nPro - step 2 of 4: create or upgrade the schema (EF Core migrations: $migrations). Idempotent.
  Generated by deploy/sql/generate-schema.ps1 on $(Get-Date -Format 'yyyy-MM-dd') - do not edit by hand.
  Run as the database owner (not the app login), for every release:
    sqlcmd -S <server> -E -b -I -d Npro -i 02-schema.sql
  Each migration runs only if it is not yet in __EFMigrationsHistory.
  The "maximum key length" warnings for the AspNet* tables are expected (ASP.NET Core Identity keys).
*/
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET ARITHABORT ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET NUMERIC_ROUNDABORT OFF;
GO

"@
$body = (Get-Content $tmp -Raw -Encoding utf8).TrimStart([char]0xFEFF)
[IO.File]::WriteAllText($out, $header + $body, (New-Object Text.UTF8Encoding $false))
Remove-Item $tmp
Write-Host "Wrote $out ($migrations)"
